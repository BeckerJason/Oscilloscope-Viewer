#include "VectorText.h"
#include <ctype.h>


// ============================================================
// Add one independent line segment
// ============================================================

void VectorText::line(
    std::vector<VectorPoint>& output,
    float x1,
    float y1,
    float x2,
    float y2
)
{
    // Move to start without drawing
    output.push_back({
        x1,
        y1,
        true
    });

    // Draw to end
    output.push_back({
        x2,
        y2,
        false
    });
}


// ============================================================
// Create complete text string
// ============================================================

std::vector<VectorPoint> VectorText::create(
    const String& text,
    float x,
    float y,
    float scale,
    float spacing
)
{
    std::vector<VectorPoint> output;

    float cursorX = x;
    float cursorY = y;

    // Character dimensions are based on a 1 x 1 coordinate system.
    float characterWidth = scale;
    float advance = characterWidth + spacing;

    for (size_t i = 0; i < text.length(); i++) {

        char c = toupper((unsigned char)text[i]);

        // New line
        if (c == '\n') {
            cursorX = x;
            cursorY += scale * 1.5f;
            continue;
        }

        // Space
        if (c == ' ') {
            cursorX += advance;
            continue;
        }

        addCharacter(
            c,
            cursorX,
            cursorY,
            scale,
            output
        );

        cursorX += advance;
    }

    return output;
}


// ============================================================
// Character generator
//
// Coordinates:
//
//       0,0 ------- 1,0
//        |           |
//        |           |
//       0,.5 ------ 1,.5
//        |           |
//        |           |
//       0,1 ------- 1,1
//
// ============================================================

void VectorText::addCharacter(
    char c,
    float x,
    float y,
    float s,
    std::vector<VectorPoint>& o
)
{
    // Convert normalized coordinates into actual coordinates.

    auto L = [&](float x1, float y1, float x2, float y2)
    {
        line(
            o,
            x + x1 * s,
            y + y1 * s,
            x + x2 * s,
            y + y2 * s
        );
    };


    switch (c) {

        // ====================================================
        // A
        // ====================================================

        case 'A':
            L(0, 1,   0.5, 0);
            L(0.5, 0, 1, 1);
            L(0.2, .55, .8, .55);
            break;


        // ====================================================
        // B
        // ====================================================

        case 'B':
            L(0, 0, 0, 1);

            L(0, 0, .65, 0);
            L(.65, 0, 1, .25);
            L(1, .25, .65, .5);
            L(.65, .5, 0, .5);

            L(0, .5, .65, .5);
            L(.65, .5, 1, .75);
            L(1, .75, .65, 1);
            L(.65, 1, 0, 1);
            break;


        // ====================================================
        // C
        // ====================================================

        case 'C':
            L(1, 0, .2, 0);
            L(.2, 0, 0, .2);
            L(0, .2, 0, .8);
            L(0, .8, .2, 1);
            L(.2, 1, 1, 1);
            break;


        // ====================================================
        // D
        // ====================================================

        case 'D':
            L(0, 0, 0, 1);
            L(0, 0, .65, 0);
            L(.65, 0, 1, .25);
            L(1, .25, 1, .75);
            L(1, .75, .65, 1);
            L(.65, 1, 0, 1);
            break;


        // ====================================================
        // E
        // ====================================================

        case 'E':
            L(0, 0, 0, 1);
            L(0, 0, 1, 0);
            L(0, .5, .8, .5);
            L(0, 1, 1, 1);
            break;


        // ====================================================
        // F
        // ====================================================

        case 'F':
            L(0, 0, 0, 1);
            L(0, 0, 1, 0);
            L(0, .5, .8, .5);
            break;


        // ====================================================
        // G
        // ====================================================

        case 'G':
            L(1, .2, .8, 0);
            L(.8, 0, .2, 0);
            L(.2, 0, 0, .2);
            L(0, .2, 0, .8);
            L(0, .8, .2, 1);
            L(.2, 1, .8, 1);
            L(.8, 1, 1, .8);
            L(1, .8, 1, .55);
            L(1, .55, .55, .55);
            break;


        // ====================================================
        // H
        // ====================================================

        case 'H':
            L(0, 0, 0, 1);
            L(1, 0, 1, 1);
            L(0, .5, 1, .5);
            break;


        // ====================================================
        // I
        // ====================================================

        case 'I':
            L(0, 0, 1, 0);
            L(.5, 0, .5, 1);
            L(0, 1, 1, 1);
            break;


        // ====================================================
        // J
        // ====================================================

        case 'J':
            L(0, 0, 1, 0);
            L(.75, 0, .75, .8);
            L(.75, .8, .55, 1);
            L(.55, 1, .2, 1);
            L(.2, 1, 0, .8);
            break;


        // ====================================================
        // K
        // ====================================================

        case 'K':
            L(0, 0, 0, 1);
            L(0, .5, 1, 0);
            L(0, .5, 1, 1);
            break;


        // ====================================================
        // L
        // ====================================================

        case 'L':
            L(0, 0, 0, 1);
            L(0, 1, 1, 1);
            break;


        // ====================================================
        // M
        // ====================================================

        case 'M':
            L(0, 1, 0, 0);
            L(0, 0, .5, .5);
            L(.5, .5, 1, 0);
            L(1, 0, 1, 1);
            break;


        // ====================================================
        // N
        // ====================================================

        case 'N':
            L(0, 1, 0, 0);
            L(0, 0, 1, 1);
            L(1, 1, 1, 0);
            break;


        // ====================================================
        // O
        // ====================================================

        case 'O':
            L(.2, 0, .8, 0);
            L(.8, 0, 1, .2);
            L(1, .2, 1, .8);
            L(1, .8, .8, 1);
            L(.8, 1, .2, 1);
            L(.2, 1, 0, .8);
            L(0, .8, 0, .2);
            L(0, .2, .2, 0);
            break;


        // ====================================================
        // P
        // ====================================================

        case 'P':
            L(0, 1, 0, 0);
            L(0, 0, .7, 0);
            L(.7, 0, 1, .2);
            L(1, .2, 1, .35);
            L(1, .35, .7, .5);
            L(.7, .5, 0, .5);
            break;


        // ====================================================
        // Q
        // ====================================================

        case 'Q':
            L(.2, 0, .8, 0);
            L(.8, 0, 1, .2);
            L(1, .2, 1, .8);
            L(1, .8, .8, 1);
            L(.8, 1, .2, 1);
            L(.2, 1, 0, .8);
            L(0, .8, 0, .2);
            L(0, .2, .2, 0);
            L(.55, .6, 1, 1);
            break;


        // ====================================================
        // R
        // ====================================================

        case 'R':
            L(0, 1, 0, 0);
            L(0, 0, .7, 0);
            L(.7, 0, 1, .2);
            L(1, .2, 1, .35);
            L(1, .35, .7, .5);
            L(.7, .5, 0, .5);
            L(.55, .5, 1, 1);
            break;


        // ====================================================
        // S
        // ====================================================

        case 'S':
            L(1, 0, .2, 0);
            L(.2, 0, 0, .2);
            L(0, .2, 0, .4);
            L(0, .4, .2, .5);
            L(.2, .5, .8, .5);
            L(.8, .5, 1, .6);
            L(1, .6, 1, .8);
            L(1, .8, .8, 1);
            L(.8, 1, 0, 1);
            break;


        // ====================================================
        // T
        // ====================================================

        case 'T':
            L(0, 0, 1, 0);
            L(.5, 0, .5, 1);
            break;


        // ====================================================
        // U
        // ====================================================

        case 'U':
            L(0, 0, 0, .8);
            L(0, .8, .2, 1);
            L(.2, 1, .8, 1);
            L(.8, 1, 1, .8);
            L(1, .8, 1, 0);
            break;


        // ====================================================
        // V
        // ====================================================

        case 'V':
            L(0, 0, .5, 1);
            L(.5, 1, 1, 0);
            break;


        // ====================================================
        // W
        // ====================================================

        case 'W':
            L(0, 0, .2, 1);
            L(.2, 1, .5, .55);
            L(.5, .55, .8, 1);
            L(.8, 1, 1, 0);
            break;


        // ====================================================
        // X
        // ====================================================

        case 'X':
            L(0, 0, 1, 1);
            L(1, 0, 0, 1);
            break;


        // ====================================================
        // Y
        // ====================================================

        case 'Y':
            L(0, 0, .5, .5);
            L(1, 0, .5, .5);
            L(.5, .5, .5, 1);
            break;


        // ====================================================
        // Z
        // ====================================================

        case 'Z':
            L(0, 0, 1, 0);
            L(1, 0, 0, 1);
            L(0, 1, 1, 1);
            break;


        // ====================================================
        // 0
        // ====================================================

        case '0':
            L(.2, 0, .8, 0);
            L(.8, 0, 1, .2);
            L(1, .2, 1, .8);
            L(1, .8, .8, 1);
            L(.8, 1, .2, 1);
            L(.2, 1, 0, .8);
            L(0, .8, 0, .2);
            L(0, .2, .2, 0);
            L(.2, .8, .8, .2);
            break;


        // ====================================================
        // 1
        // ====================================================

        case '1':
            L(.25, .2, .5, 0);
            L(.5, 0, .5, 1);
            L(.2, 1, .8, 1);
            break;


        // ====================================================
        // 2
        // ====================================================

        case '2':
            L(0, .2, .2, 0);
            L(.2, 0, .8, 0);
            L(.8, 0, 1, .2);
            L(1, .2, 1, .4);
            L(1, .4, 0, 1);
            L(0, 1, 1, 1);
            break;


        // ====================================================
        // 3
        // ====================================================

        case '3':
            L(0, 0, .8, 0);
            L(.8, 0, 1, .2);
            L(1, .2, .7, .5);
            L(.7, .5, 1, .8);
            L(1, .8, .8, 1);
            L(.8, 1, 0, 1);
            break;


        // ====================================================
        // 4
        // ====================================================

        case '4':
            L(.8, 1, .8, 0);
            L(.8, 0, 0, .65);
            L(0, .65, 1, .65);
            break;


        // ====================================================
        // 5
        // ====================================================

        case '5':
            L(1, 0, 0, 0);
            L(0, 0, 0, .5);
            L(0, .5, .8, .5);
            L(.8, .5, 1, .7);
            L(1, .7, 1, .8);
            L(1, .8, .8, 1);
            L(.8, 1, 0, 1);
            break;


        // ====================================================
        // 6
        // ====================================================

        case '6':
            L(1, 0, .2, 0);
            L(.2, 0, 0, .2);
            L(0, .2, 0, .8);
            L(0, .8, .2, 1);
            L(.2, 1, .8, 1);
            L(.8, 1, 1, .8);
            L(1, .8, 1, .6);
            L(1, .6, .8, .5);
            L(.8, .5, 0, .5);
            break;


        // ====================================================
        // 7
        // ====================================================

        case '7':
            L(0, 0, 1, 0);
            L(1, 0, .35, 1);
            break;


        // ====================================================
        // 8
        // ====================================================

        case '8':
            L(.2, 0, .8, 0);
            L(.8, 0, 1, .2);
            L(1, .2, .8, .5);
            L(.8, .5, .2, .5);
            L(.2, .5, 0, .2);
            L(0, .2, .2, 0);

            L(.2, .5, 0, .8);
            L(0, .8, .2, 1);
            L(.2, 1, .8, 1);
            L(.8, 1, 1, .8);
            L(1, .8, .8, .5);
            break;


        // ====================================================
        // 9
        // ====================================================

        case '9':
            L(1, .5, .2, .5);
            L(.2, .5, 0, .3);
            L(0, .3, 0, .2);
            L(0, .2, .2, 0);
            L(.2, 0, .8, 0);
            L(.8, 0, 1, .2);
            L(1, .2, 1, .8);
            L(1, .8, .8, 1);
            L(.8, 1, 0, 1);
            break;


        // ====================================================
        // -
        // ====================================================

        case '-':
            L(.15, .5, .85, .5);
            break;


        // ====================================================
        // .
        // ====================================================

        case '.':
            L(.45, .95, .55, .95);
            break;


        // ====================================================
        // :
        // ====================================================

        case ':':
            L(.45, .3, .55, .3);
            L(.45, .75, .55, .75);
            break;


        // ====================================================
        // !
        // ====================================================

        case '!':
            L(.5, 0, .5, .7);
            L(.45, .95, .55, .95);
            break;


        // ====================================================
        // /
        // ====================================================

        case '/':
            L(0, 1, 1, 0);
            break;


        // Unknown character
        default:
            break;
    }
}